// Builds src/world.js, the dashboard's world map: one SVG path per country,
// keyed by ISO 3166 alpha-2 (the code Cloudflare reports), in the Equal Earth
// projection. Data: Natural Earth 1:110m via world-atlas (public domain).
// Run after changing the map: node scripts/make-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoEqualEarth, geoPath } from 'd3-geo';
import countries from 'i18n-iso-countries';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'));
const world = feature(topo, topo.objects.countries);
world.features = world.features.filter((f) => f.properties.name !== 'Antarctica');

export const WIDTH = 1000;
const projection = geoEqualEarth().fitWidth(WIDTH, world);
const height = Math.ceil(geoPath(projection).bounds(world)[1][1]);
// Whole pixels: at 1000px wide that is finer than the 1:110m data.
const path = geoPath(projection).digits(0);

// Areas with no numeric code that Cloudflare still names.
const EXTRA = { Kosovo: 'XK' };

const shapes = [];
for (const f of world.features) {
  // Natural Earth leaves a few disputed areas without a numeric code; their
  // visits still count in the country list, they just have no shape here.
  const id = (f.id && countries.numericToAlpha2(f.id)) || EXTRA[f.properties.name];
  const d = path(f);
  if (d) shapes.push([id || '', f.properties.name, d]);
}

writeFileSync(
  new URL('../src/world.js', import.meta.url),
  `// Generated by scripts/make-map.mjs from Natural Earth 1:110m (public domain). Do not edit.\n` +
    `export const MAP = { width: ${WIDTH}, height: ${height} };\n` +
    `// [ISO alpha-2 or '', name, SVG path]\n` +
    `export const SHAPES = ${JSON.stringify(shapes)};\n`,
);
console.log(`${shapes.filter((s) => !s[0]).map((s) => s[1])} unnamed; ${shapes.length} countries, ${height}px tall, ${(JSON.stringify(shapes).length / 1024).toFixed(0)} KB`);
